#!/usr/bin/env bash
# Place the per-project agent docs (agents/<project>/AGENTS.md, the source of
# truth) into each submodule checkout without committing them to the fork:
#
#   <project>/CLAUDE.local.md   "@../agents/<project>/AGENTS.md" import, so
#                               Claude Code reads the source directly. Used
#                               instead of CLAUDE.md, which a project may track.
#   <project>/AGENTS.md         generated copy for Codex and other tools, or
#   <project>/AGENTS.override.md  when the project already tracks an AGENTS.md
#                               (upstream's text first, then ours).
#
# All of them are listed in the submodule's info/exclude.
#
# Usage: sync-agent-docs.sh [--check]
#   --check  only report drift (exit 1 if any file is missing or stale)
set -euo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/common/lib.sh"
cd "$STACK_ROOT"

check=0
[[ "${1:-}" == --check ]] && check=1
drift=0

# want <file> <content>: write (or in --check mode compare) a generated file.
want() {
    if [[ -f "$1" ]] && [[ "$(cat "$1")" == "$2" ]]; then
        return
    fi
    if (( check )); then
        echo "stale: $1"
        drift=1
    else
        printf '%s\n' "$2" > "$1"
        echo "wrote: $1"
    fi
}

for p in $STACK_PROJECTS; do
    src="agents/$p/AGENTS.md"
    [[ -f "$src" && -e "$p/.git" ]] || continue
    header="<!-- GENERATED by scripts/sync-agent-docs.sh. Edit $src in the MediaStack superrepo, not this file. -->"

    if git -C "$p" ls-files --error-unmatch AGENTS.md >/dev/null 2>&1; then
        target=AGENTS.override.md
        content="$header"$'\n\n'"$(git -C "$p" show HEAD:AGENTS.md)"$'\n\n---\n\n'"$(cat "$src")"
    else
        target=AGENTS.md
        content="$header"$'\n\n'"$(cat "$src")"
    fi
    want "$p/$target" "$content"
    want "$p/CLAUDE.local.md" "@../agents/$p/AGENTS.md"

    exclude=$(git -C "$p" rev-parse --git-path info/exclude)
    [[ "$exclude" = /* ]] || exclude="$p/$exclude"
    for f in "/$target" /CLAUDE.local.md; do
        if ! grep -qxF "$f" "$exclude" 2>/dev/null; then
            if (( check )); then
                echo "not excluded: $p$f"
                drift=1
            else
                mkdir -p "$(dirname "$exclude")"
                echo "$f" >> "$exclude"
            fi
        fi
    done
done

exit $drift
